    # Merge
    # ------------------------------------------------------------------

    def _auto_commit_worktree(self, spec_id: str, task_id: str, task_title: str = "") -> AutoCommitResult:
        """Commit any uncommitted changes in a task worktree before merging.

        Safety net for agents that write files but forget to git commit.

        Defence-in-depth against merge-time auto-commit pollution.  A
        stale ``.gitignore`` (one missing ``.venv*/``) lets
        ``git add -A`` drag an entire venv into the task branch — a real
        incident swept 4,738 files through every later merge.  Three
        layers, each independent of ``.gitignore``:

        1. **Generated-path reset** — unstages harness/MCP configs and
           worktree-local runtime paths (existing F24 guard).
        2. **Pollution blocklist** — unstages venv markers
           (``pyvenv.cfg`` roots, ``.venv*``, ``venv``), ``node_modules``,
           ``site-packages``, ``__pycache__`` at any depth.
        3. **Bulk-add guard** — if more than
           ``_AUTO_COMMIT_MAX_NEW_FILES`` NEW untracked files would be
           committed, refuses the bulk and commits only tracked
           modifications, catching pollution the blocklist doesn't name.

        Every exclusion is logged at WARNING level and reported in the
        returned :class:`AutoCommitResult` — never silent.

        Returns an ``AutoCommitResult`` (truthy iff a commit was created).
        """
        worktree_path = self.get_worktree_path(spec_id, task_id)
        if not worktree_path.exists():
            return AutoCommitResult()

        # Check for any changes (staged, unstaged, or untracked)
        status = self._git("status", "--porcelain", cwd=worktree_path)
        if not status.stdout.strip():
            return AutoCommitResult()

        logger.warning(
            "Task %s has uncommitted changes in worktree — auto-committing",
            task_id,
        )

        # Stage everything EXCEPT .proof/ — pathspec exclude is the
        # primary mechanism so proof artifacts are never in the index.
        # The reset below (Layer 1) is defence-in-depth for anything the
        # pathspec might miss.  An agent must never be able to lose a
        # task because the harness swept .proof/ into a commit.
        self._git("add", "-A", ".", ":(exclude).proof", cwd=worktree_path)

        # Layer 1 — unstage every generated/runtime path that must never
        # be committed.  Single source of truth derived from the harness/
        # MCP config writers plus worktree-local runtime paths.
        reset_args: List[str] = [
            "--",
            ".gitignore",
            *HARNESS_GENERATED_PATHS,
            *_WORKTREE_LOCAL_PATHS,
        ]
        self._git("reset", *reset_args, cwd=worktree_path)

        # Snapshot what remains staged after layer 1.
        cached = self._git("diff", "--cached", "--name-only", cwd=worktree_path)
        staged_paths = [p for p in cached.stdout.splitlines() if p.strip()]
        if not staged_paths:
            return AutoCommitResult()

        # Layer 2 — pollution blocklist.  Detect venv roots via the
        # ``pyvenv.cfg`` marker (catches non-standard names like ``env/``),
        # then unstage every staged file that is venv/build pollution.
        venv_roots = _find_venv_roots(staged_paths)
        blocklisted = [p for p in staged_paths if _is_pollution_path(p, venv_roots)]
        for i in range(0, len(blocklisted), _RESET_BATCH_SIZE):
            batch = blocklisted[i : i + _RESET_BATCH_SIZE]
            self._git("reset", "--", *batch, cwd=worktree_path)

        # Layer 3 — bulk-add guard.  Distinguish NEW files (status ``A``)
        # from tracked modifications; if there are too many new ones,
        # unstage them all and keep only the tracked modifications.
        cached_ns = self._git("diff", "--cached", "--name-status", cwd=worktree_path)
        new_files: List[str] = []
        for line in cached_ns.stdout.splitlines():
            if not line.strip():
                continue
            code = line[0]
            if code != "A":
                continue
            # Format: "<status>\t<path>" (renames have extra tabs; rare here).
            new_files.append(line.split("\t", 1)[1] if "\t" in line else line[2:])
        skipped_bulk = 0
        if len(new_files) > _AUTO_COMMIT_MAX_NEW_FILES:
            for i in range(0, len(new_files), _RESET_BATCH_SIZE):
                batch = new_files[i : i + _RESET_BATCH_SIZE]
                self._git("reset", "--", *batch, cwd=worktree_path)
            skipped_bulk = len(new_files)

        result = AutoCommitResult(
            skipped_blocklist=len(blocklisted),
            skipped_bulk=skipped_bulk,
        )

        # If nothing is left staged after all guards, bail out — but
        # report the exclusions loudly so the operator sees pollution
        # was refused even when no real work accompanied it.
        staged = self._git("diff", "--cached", "--name-only", cwd=worktree_path)
        if not staged.stdout.strip():
            if result.skipped:
                logger.warning(
                    "Auto-commit for task %s excluded %d file(s) and no "
                    "tracked modifications remained — nothing committed. %s",
                    task_id, result.skipped, result.summary,
                )
            return result

        msg = f"Auto-commit task {task_id}: {task_title}" if task_title else f"Auto-commit task {task_id}"
        msg += _provenance_trailers(spec_id, task_id)
        commit = self._git("commit", "-m", msg, cwd=worktree_path)
        if commit.returncode != 0:
            logger.warning("Auto-commit failed for task %s: %s", task_id, commit.stderr.strip())
            return result

        result.committed = True
        if result.skipped:
            logger.warning(
                "Auto-committed task %s with %d exclusion(s): %s",
                task_id, result.skipped, result.summary,
            )
        else:
            logger.info("Auto-committed uncommitted work for task %s", task_id)
        return result

    def merge_task_into_spec(
        self,
        spec_id: str,
        task_id: str,
        task_title: str = "",
        attempt_resolution: bool = False,
        resolution_guidance: str = "",
    ) -> MergeResult:
        """Merge a task branch into the spec branch.

        Auto-commits any uncommitted work in the task worktree first,
        then uses a file lock to serialize merges within the same spec.

        When ``attempt_resolution`` is True, mechanical conflicts
        (generated agent configs) are auto-resolved by the merge agent
        instead of leaving the task stuck.  See :mod:`odin.merge_agent`.

        ``resolution_guidance`` is a human's free-text reply to a prior
        ambiguous-conflict question — when set, it's applied to any
        ambiguous conflicts instead of escalating unconditionally
        (:func:`odin.merge_agent.resolve_ambiguous_with_guidance`).
        """
        spec_branch = f"spec/{spec_id}"
        task_branch = f"task/{spec_id}/{task_id}"

        if not self._branch_exists(task_branch):
            return MergeResult(success=False, error=f"Task branch {task_branch} does not exist")

        # Safety net: commit any uncommitted work before merging
        self._auto_commit_worktree(spec_id, task_id, task_title)

        lock = self._spec_lock(spec_id)
        try:
            with lock:
                return self._do_merge(
                    spec_branch, task_branch, task_id, task_title,
                    attempt_resolution=attempt_resolution,
                    task_brief=task_title,
                    resolution_guidance=resolution_guidance,
                )
        except Exception as exc:
            logger.exception("Merge failed for task %s into spec %s", task_id, spec_id)
            return MergeResult(success=False, error=str(exc))

    def _do_merge(
        self,
        spec_branch: str,
        task_branch: str,
        task_id: str,
        task_title: str,
        attempt_resolution: bool = False,
        task_brief: str = "",
        resolution_guidance: str = "",
    ) -> MergeResult:
        """Perform the actual merge (called under lock).

        Prefers the _spec worktree if it exists (the spec branch is already
        checked out there). Falls back to creating a temporary merge worktree
        for specs that predate the _spec worktree feature.
        """
        spec_id = spec_branch.removeprefix("spec/")
        spec_wt = self.worktree_base / spec_id / "_spec"
        use_spec_wt = spec_wt.exists() and (spec_wt / ".git").exists()

        if use_spec_wt:
            return self._merge_in_worktree(
                spec_wt, spec_branch, task_branch, task_id, task_title,
                attempt_resolution=attempt_resolution,
                task_brief=task_brief,
                resolution_guidance=resolution_guidance,
            )

        # Fallback: create a temporary merge worktree (older specs without _spec)
        merge_wt = self.worktree_base / "_merge" / f"spec_{spec_id}"
        if merge_wt.exists():
            self._git("worktree", "remove", "--force", str(merge_wt))

        try:
            merge_wt.parent.mkdir(parents=True, exist_ok=True)
            result = self._git("worktree", "add", str(merge_wt), spec_branch)
            if result.returncode != 0:
                return MergeResult(
                    success=False,
                    error=f"worktree add failed: {result.stderr}",
                )
            return self._merge_in_worktree(
                merge_wt, spec_branch, task_branch, task_id, task_title,
                attempt_resolution=attempt_resolution,
                task_brief=task_brief,
                resolution_guidance=resolution_guidance,
            )
        finally:
            if merge_wt.exists():
                self._git("worktree", "remove", "--force", str(merge_wt))

    def _strip_proof_from_merge_result(self, worktree: Path) -> bool:
        """Remove ``.proof/`` from the merge commit so it never reaches the spec branch.

        Agents write ``.proof/task-<id>/`` as per-task evidence.  It belongs on
        the task board (uploaded as attachments), not in the
        shared spec-branch git history.  The merge ``--no-ff`` is the single
        choke point where all task-branch content enters the spec branch, so
        stripping here covers both committed and uncommitted ``.proof/``
        regardless of how it arrived on the task branch — the mechanism
        cannot half-apply.

        ``git rm -r --cached`` removes ``.proof/`` from the index while
        leaving the working-tree files intact (the proof uploader reads them
        from the task worktree on disk).  ``--ignore-unmatch`` makes the call
        a no-op when ``.proof/`` is absent, so tasks with no proof files are
        unaffected.
        """
        rm = self._git(
            "rm", "-r", "--cached", "--ignore-unmatch", ".proof", cwd=worktree,
        )
        if rm.returncode != 0:
            logger.warning("Failed to strip .proof/ from merge result: %s", rm.stderr.strip())
            return False
        if not rm.stdout.strip():
            return False
        amend = self._git("commit", "--amend", "--no-edit", cwd=worktree)
        if amend.returncode != 0:
            logger.warning(
                "Failed to amend merge commit after .proof/ strip: %s",
                amend.stderr.strip(),
            )
            return False
        logger.info("Stripped .proof/ from merge result before push")
        return True

    def _changed_paths_since(self, worktree: Path, since_ref: str) -> List[str]:
        """List paths changed by ``since_ref..HEAD`` — added, copied,
        modified, renamed, or type-changed (NOT deleted; the gate
        ignores missing files anyway, but excluding them here keeps
        the result list lean and the contract explicit).

        Used by the post-merge safety gate (task 338) so it only
        inspects files the merge commit actually touched.
        """
        result = self._git(
            "diff", "--name-only", "--diff-filter=ACMRT",
            since_ref, "HEAD", cwd=worktree,
        )
        if result.returncode != 0:
            logger.warning(
                "Post-merge gate: failed to list changed paths: %s",
                result.stderr.strip(),
            )
            return []
        return [line for line in result.stdout.splitlines() if line.strip()]

    def _run_post_merge_gate(
        self,
        worktree: Path,
        diff_stat: Optional[str],
        task_branch: str,
        spec_branch: str,
        task_id: str,
    ) -> List[Tuple[str, str, int]]:
        """Run the post-merge safety gate against the merge commit.

        Walks every path the merge commit added/copied/modified/
        renamed/type-changed; runs :func:`odin.merge_agent._check_post_merge_files`
        against them; returns the violation list (empty on clean).
        The actual merge commit reset is the caller's responsibility
        so this function stays pure — easier to test.
        """
        # Local import keeps the merge-agent dependency one-way:
        # worktree → merge_agent. Avoids an import cycle in test
        # contexts that stub one without the other.
        from odin.merge_agent import _check_post_merge_files

        paths = self._changed_paths_since(worktree, "HEAD~1")
        if not paths:
            return []
        violations = _check_post_merge_files(worktree, paths)
        if violations:
            logger.warning(
                "Post-merge gate refused merge of %s into %s for task %s: %s",
                task_branch, spec_branch, task_id, violations,
            )
        return violations

    def _apply_merge_migration_fix(
        self,
        worktree: Path,
        conflict_check: "MigrationConflictCheck",
        spec_branch: str,
        task_id: str,
        diff_stat: Optional[str],
    ) -> Optional[MergeResult]:
        """Run the bounded ``makemigrations --merge`` fix for a migration
        leaf collision and fold the new migration into the merge commit.

        Returns a successful ``MergeResult`` when the graph is linear after
        the fix, or ``None`` when it fails (caller parks the task for a
        human).  ``--noinput`` makes Django 5.x proceed non-interactively:
        it swaps in ``MigrationQuestioner(defaults={"ask_merge": True})``
        which auto-confirms the merge.

        Called automatically by the merge gate whenever a leaf collision is
        detected (no human in the loop): ``makemigrations --merge`` creates
        a NEW migration file that Django generates deterministically — it
        never edits or renames existing files — so it is safe to run without
        confirmation.  Reserving distinct numeric prefixes at dispatch does
        not prevent leaf collisions (two parallel migrations always yield two
        leaves regardless of prefix), so this is the single mechanism.
        """
        backend = worktree / _DJANGO_BACKEND_REL_PATH
        merge_run = subprocess.run(
            ["python3", "manage.py", "makemigrations", "--merge", "--noinput"],
            cwd=str(backend),
            capture_output=True,
            text=True,
            timeout=60,
        )
        if merge_run.returncode != 0:
            logger.warning(
                "makemigrations --merge failed in %s: %s",
                backend, (merge_run.stderr or merge_run.stdout).strip(),
            )
            return None

        # Find the new untracked migration file(s) Django just wrote.
        status = self._git("status", "--porcelain", cwd=worktree)
        new_migrations = [
            line[3:].strip()
            for line in status.stdout.splitlines()
            if line.startswith("??") and "migrations/" in line and line[3:].strip().endswith(".py")
        ]
        if not new_migrations:
            logger.warning(
                "makemigrations --merge produced no new migration file in %s",
                worktree,
            )
            return None

        # Stage + amend so the merge migration travels inside the merge
        # commit (never a loose follow-up that a later reset would drop).
        for path in new_migrations:
            self._git("add", path, cwd=worktree)
        amend = self._git("commit", "--amend", "--no-edit", cwd=worktree)
        if amend.returncode != 0:
            logger.warning(
                "Failed to amend merge commit with merge migration: %s",
                amend.stderr.strip(),
            )
            return None

        # Re-check: the graph must now be linear before we push.
        recheck = _check_django_migration_conflicts(worktree)
        if recheck.has_conflict:
            logger.warning(
                "Migration collision persists after makemigrations --merge "
                "in %s: leaves=%s", worktree, recheck.leaves,
            )
            return None

        push = self._git("push", "origin", spec_branch, cwd=worktree)
        if push.returncode != 0:
            logger.warning(
                "Failed to push after merge-migration fix: %s",
                push.stderr.strip(),
            )

        leaves = list(conflict_check.leaves)
        rationale = (
            f"Created Django merge migration for leaf collision "
            f"({', '.join(leaves)}) via makemigrations --merge."
        )
        logger.info(
            "Migration leaf collision resolved via makemigrations --merge "
            "for task %s: %s", task_id, new_migrations,
        )
        return MergeResult(
            success=True,
            diff_stat=diff_stat,
            resolved_files=new_migrations,
            resolution_rationale=rationale,
        )

    def _merge_in_worktree(
        self,
        worktree: Path,
        spec_branch: str,
        task_branch: str,
        task_id: str,
        task_title: str,
        attempt_resolution: bool = False,
        task_brief: str = "",
        resolution_guidance: str = "",
    ) -> MergeResult:
        """Merge a task branch into the spec branch inside the given worktree.

        When ``attempt_resolution`` is True and a conflict occurs, the
        merge agent (:mod:`odin.merge_agent`) is invoked to resolve
        mechanical conflicts in-place.  Ambiguous conflicts abort the
        merge as before.
        """
        # Fetch and pull latest spec branch
        self._git("fetch", "origin", spec_branch)
        self._git("pull", "origin", spec_branch, cwd=worktree)

        # Capture diff stat before merge (spec..task shows what the task added)
        diff_stat_result = self._git(
            "diff", "--stat", f"{spec_branch}...{task_branch}", cwd=worktree,
        )
        diff_stat = diff_stat_result.stdout.strip() if diff_stat_result.returncode == 0 else None

        # Detect no-op: if the task branch has no commits beyond the spec branch,
        # there's nothing to merge. Don't lie about it.
        if not diff_stat:
            logger.warning(
                "Task %s has no changes vs spec branch — nothing to merge", task_id,
            )
            return MergeResult(success=True, noop=True)

        # Clean untracked agent configs to prevent merge conflicts
        self._clean_untracked_agent_configs(worktree)

        # Merge task branch
        spec_id = spec_branch.removeprefix("spec/")
        trailer = _provenance_trailers(spec_id, task_id)
        msg = f"Merge task {task_id}: {task_title}" if task_title else f"Merge task {task_id}"
        result = self._git("merge", "--no-ff", task_branch, "-m", msg + trailer, cwd=worktree)
        if result.returncode != 0:
            status = self._git("status", "--porcelain", cwd=worktree)
            status_lines = status.stdout.splitlines()
            conflicting_files = self._parse_conflicting_files(status_lines)
            has_conflicts = bool(conflicting_files)
            if has_conflicts:
                # Attempt merge-agent resolution if enabled
                if attempt_resolution:
                    from odin.merge_agent import resolve_conflicts_in_worktree

                    resolution = resolve_conflicts_in_worktree(
                        self, worktree, conflicting_files, task_brief,
                        resolution_guidance=resolution_guidance,
                        task_id=task_id,
                    )
                    if resolution.resolved:
                        # Complete the merge commit
                        commit_result = self._git(
                            "commit", "--no-edit", "-m",
                            msg + f"\n\nMerge agent resolution: {resolution.rationale}" + trailer,
                            cwd=worktree,
                        )
                        if commit_result.returncode == 0:
                            # Post-merge safety gate (task 338): the
                            # merge agent's resolution has landed;
                            # before pushing, run the cheapest honest
                            # checks against the files it touched.
                            # If markers / syntax errors survived, roll
                            # the commit back and refuse the merge so
                            # a broken state never reaches the spec
                            # branch.
                            gate_violations = self._run_post_merge_gate(
                                worktree, diff_stat, task_branch,
                                spec_branch, task_id,
                            )
                            if gate_violations:
                                reset = self._git("reset", "--hard", "HEAD~1", cwd=worktree)
                                if reset.returncode != 0:
                                    logger.error(
                                        "Failed to roll back merge commit "
                                        "after gate violation for task %s: %s",
                                        task_id, reset.stderr.strip(),
                                    )
                                logger.warning(
                                    "Post-merge gate refused merge of %s into "
                                    "%s for task %s: %d violation(s)",
                                    task_branch, spec_branch, task_id,
                                    len(gate_violations),
                                )
                                return MergeResult(
                                    success=False,
                                    conflict=True,
                                    needs_human=True,
                                    error=(
                                        f"Post-merge safety gate refused: "
                                        f"{len(gate_violations)} violation(s) "
                                        f"in resolved files"
                                    ),
                                    diff_stat=diff_stat,
                                    conflicting_files=list(
                                        {v[0] for v in gate_violations}
                                    ),
                                    resolved_files=[],
                                    resolution_rationale=resolution.rationale,
                                    gate_violations=list(gate_violations),
                                    agent_model=resolution.agent_model,
                                    token_usage=dict(resolution.token_usage),
                                )
                            self._strip_proof_from_merge_result(worktree)
                            push = self._git("push", "origin", spec_branch, cwd=worktree)
                            if push.returncode != 0:
                                logger.warning(
                                    "Failed to push spec branch after resolution: %s",
                                    push.stderr.strip(),
                                )
                            logger.info(
                                "Merge agent resolved %d conflict(s) for %s",
                                len(resolution.mechanical_files), task_id,
                            )
                            return MergeResult(
                                success=True,
                                diff_stat=diff_stat,
                                resolved_files=resolution.mechanical_files,
                                resolution_rationale=resolution.rationale,
                                agent_model=resolution.agent_model,
                                token_usage=dict(resolution.token_usage),
                            )
                        # Commit failed — fall through to abort
                        logger.warning(
                            "Merge-agent commit failed: %s",
                            commit_result.stderr.strip(),
                        )

                    if resolution.needs_human:
                        self._git("merge", "--abort", cwd=worktree)
                        return MergeResult(
                            success=False,
                            conflict=True,
                            error=f"Merge conflict (needs human): {resolution.rationale or 'ambiguous'}",
                            diff_stat=diff_stat,
                            conflicting_files=conflicting_files,
                            ambiguous_files=resolution.ambiguous_files,
                            resolved_files=[],
                            resolution_rationale=resolution.rationale,
                            needs_human=True,
                            conflict_hunks=dict(resolution.conflict_hunks),
                            file_resolutions={
                                k: dict(v) for k, v in resolution.file_resolutions.items()
                            },
                            spec_commit_messages={
                                k: list(v) for k, v in resolution.spec_commit_messages.items()
                            },
                            task_commit_messages={
                                k: list(v) for k, v in resolution.task_commit_messages.items()
                            },
                            agent_model=resolution.agent_model,
                            token_usage=dict(resolution.token_usage),
                        )

                # Standard abort path (resolution disabled or failed)
                self._git("merge", "--abort", cwd=worktree)
                return MergeResult(
                    success=False,
                    conflict=True,
                    error=f"Merge conflict: {result.stderr.strip()}",
                    diff_stat=diff_stat,
                    conflicting_files=conflicting_files,
                )
            # git reports conflict detail on stdout, not stderr — an empty
            # error string here is how task 284 vanished. Never empty.
            detail = (result.stderr or "").strip() or (result.stdout or "").strip() or "git merge aborted with no output"
            return MergeResult(success=False, error=f"merge failed: {detail}", diff_stat=diff_stat)

        # Strip per-task proof artifacts from the merge result.  .proof/
        # belongs on the task board (uploaded as attachments), not in the
        # spec-branch git history.
        self._strip_proof_from_merge_result(worktree)

        # Post-merge safety gate (task 338): cheapest honest checks on
        # the files the merge commit just landed — conflict markers and
        # Python syntax errors must not survive a merge into the shared
        # spec branch. Runs BEFORE the migration gate so a single broken
        # Python file is caught at the cheapest layer first; the
        # behavioral safety net (W5.12 spec-branch suite run) sits
        # behind both.
        gate_violations = self._run_post_merge_gate(
            worktree, diff_stat, task_branch, spec_branch, task_id,
        )
        if gate_violations:
            reset = self._git("reset", "--hard", "HEAD~1", cwd=worktree)
            if reset.returncode != 0:
                logger.error(
                    "Failed to roll back merge commit after gate violation "
                    "for task %s: %s",
                    task_id, reset.stderr.strip(),
                )
            logger.warning(
                "Post-merge gate refused merge of %s into %s for task %s: "
                "%d violation(s)",
                task_branch, spec_branch, task_id, len(gate_violations),
            )
            return MergeResult(
                success=False,
                conflict=True,
                needs_human=True,
                error=(
                    f"Post-merge safety gate refused: "
                    f"{len(gate_violations)} violation(s) in merged files"
                ),
                diff_stat=diff_stat,
                conflicting_files=list({v[0] for v in gate_violations}),
                gate_violations=list(gate_violations),
            )

        # Migration leaf-collision gate (wave-4 recurring class).
        # Two parallel task branches can each mint a migration with the
        # same numeric prefix (``0049_a.py``, ``0049_b.py``); ``git merge
        # --no-ff`` lands them side-by-side with no content overlap, so
        # git-level conflict detection never fires.  Django's
        # ``makemigrations --check`` is the only signal that the
        # migration graph now has two leaves with no merge migration —
        # check it here so the broken state never reaches the spec
        # branch (which would then poison every sibling's backend suite
        # until a human hand-adds a merge migration).
        conflict_check = _check_django_migration_conflicts(worktree)
        if conflict_check.has_conflict:
            error = _format_migration_conflict_error(
                conflict_check.leaves, conflict_check.app,
            )
            # Auto-resolve (wave-4/6/7/8 recurring class): run the bounded
            # ``makemigrations --merge`` fix WITHOUT waiting for a human.
            # Django creates a NEW merge migration deterministically — it
            # never edits or renames existing files — so this is safe to
            # do automatically, and it is the only mechanism that actually
            # prevents the collision.  Reserving distinct numeric prefixes
            # at dispatch does NOT help: two parallel migrations always
            # produce two leaf nodes regardless of their prefix number
            # (the collision is a graph-structure problem, not a numbering
            # one — verified empirically against Django 5.1).  The gate's
            # own re-check guarantees the graph is linear before the fix
            # is accepted; on any failure the merge parks for a human.
            fixed = self._apply_merge_migration_fix(
                worktree, conflict_check, spec_branch, task_id, diff_stat,
            )
            if fixed is not None:
                return fixed
            logger.warning(
                "Auto makemigrations --merge failed for task %s — "
                "parking for human intervention", task_id,
            )
            # Fallback: undo the local merge commit (spec branch was NOT
            # pushed), surface the collision as needs_human so the
            # reply-resume listener (tasks.signals) picks up a human's
            # guidance comment and re-attempts the bounded fix.
            reset = self._git("reset", "--hard", "HEAD~1", cwd=worktree)
            if reset.returncode != 0:
                logger.error(
                    "Failed to undo local merge after migration conflict "
                    "detection in %s: %s",
                    worktree, reset.stderr.strip(),
                )
            logger.warning(
                "Aborted merge of %s into %s due to migration leaf "
                "collision: %s",
                task_branch, spec_branch, conflict_check.leaves,
            )
            return MergeResult(
                success=False,
                conflict=True,
                needs_human=True,
                migration_conflict=True,
                error=error,
                diff_stat=diff_stat,
                conflicting_files=list(conflict_check.leaves),
            )

        # Push updated spec branch
        push = self._git("push", "origin", spec_branch, cwd=worktree)
        if push.returncode != 0:
            logger.warning("Failed to push spec branch after merge: %s", push.stderr.strip())

        logger.info("Merged %s into %s", task_branch, spec_branch)
        return MergeResult(success=True, diff_stat=diff_stat)

