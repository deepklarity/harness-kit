"""Git worktree isolation for parallel task execution.

Each spec gets a branch (spec/<spec_id>) forked from main.
Each task gets a worktree with its own branch (task/<spec_id>/<task_id>)
forked from the spec branch. On task completion, the task branch is
merged back into the spec branch. On spec completion, a PR is created.

All git operations are serialized per-spec via file locks to prevent
concurrent merge races.
"""

import logging
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from odin.mcps.taskit_mcp.config import HARNESS_GENERATED_PATHS

logger = logging.getLogger("odin.worktree")

# Source paths (in project_root) copied into each worktree so agent CLIs
# find their settings.  Derived from the harness-generated paths plus
# odin's own project-level config files (``.env``, ``.odin/config.yaml``).
AGENT_CONFIG_PATHS = (
    *HARNESS_GENERATED_PATHS,
    ".odin/config.yaml",
    ".env",
)

# Worktree-local runtime paths that odin writes but should never commit
# (logs, costs, locks, specs).  These are NOT generated by harness/MCP
# config writers, so they're tracked separately from HARNESS_GENERATED_PATHS.
_WORKTREE_LOCAL_PATHS = (
    ".env",
    ".odin",
    ".proof",
)

# Defensive gitignore-only patterns for retired agents whose configs may
